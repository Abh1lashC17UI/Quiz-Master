/**
 * src/launcher.js
 *
 * Generates:
 *   1. quizmaster.conf  — placed in the quiz root folder
 *      Contains the absolute path to the QuizMaster installation.
 *      One file for the whole quiz library. If QuizMaster moves,
 *      only this file needs updating.
 *
 *   2. LaunchQuiz.bat   — placed in each quiz's own folder
 *      Reads ../quizmaster.conf to find QuizMaster, then starts
 *      the server (if not already running) and opens the host UI
 *      for the specific quiz.
 *
 * This design means moving QuizMaster only requires updating one
 * quizmaster.conf file rather than every individual quiz launcher.
 */

'use strict';

const path = require('path');
const fse  = require('fs-extra');

const CONF_FILENAME = 'quizmaster.conf';
const BAT_FILENAME  = 'LaunchQuiz.bat';

// ── quizmaster.conf ───────────────────────────────────────────────────────────

/**
 * Write (or update) quizmaster.conf in the quiz root folder.
 * @param {string} rootFolder - The quiz root folder
 * @param {string} appDir     - Absolute path to the QuizMaster installation
 */
async function writeConf(rootFolder, appDir) {
  await fse.ensureDir(rootFolder);
  const confPath = path.join(rootFolder, CONF_FILENAME);
  // Store as a plain single-line text file for maximum .bat compatibility
  await fse.writeFile(confPath, appDir, 'utf8');
}

/**
 * Read quizmaster.conf from the quiz root folder.
 * Returns null if not found.
 */
async function readConf(rootFolder) {
  const confPath = path.join(rootFolder, CONF_FILENAME);
  if (!await fse.pathExists(confPath)) return null;
  const content = await fse.readFile(confPath, 'utf8');
  return content.trim() || null;
}

// ── LaunchQuiz.bat ────────────────────────────────────────────────────────────

/**
 * Generate a LaunchQuiz.bat for a completed quiz.
 *
 * @param {string} quizDir  - Absolute path to the quiz folder
 * @param {string} quizId   - The quiz's stable UUID
 * @param {string} quizName - Human-readable quiz name (for the comment header)
 * @param {number} port     - QuizMaster server port (default 4000)
 */
async function generateLauncher(quizDir, quizId, quizName, port = 4000) {
  const bat = buildBatContent(quizId, quizName, port);
  const batPath = path.join(quizDir, BAT_FILENAME);
  await fse.writeFile(batPath, bat, 'utf8');
}

/**
 * Remove the LaunchQuiz.bat from a quiz folder (when marking incomplete).
 */
async function removeLauncher(quizDir) {
  const batPath = path.join(quizDir, BAT_FILENAME);
  if (await fse.pathExists(batPath)) {
    await fse.remove(batPath);
  }
}

/**
 * Build the .bat file content.
 *
 * Strategy:
 *  - The quiz folder is one level inside the root folder.
 *  - quizmaster.conf sits in the root folder, i.e. one level UP from the quiz.
 *  - The .bat uses %~dp0 (directory of the .bat itself) to find the quiz folder,
 *    then navigates to %~dp0.. to find quizmaster.conf.
 *  - All paths are quoted to handle spaces correctly.
 */
function buildBatContent(quizId, quizName, port) {
  // Sanitise quizName for the comment line (strip special chars)
  const safeName = quizName.replace(/[<>&|^]/g, '');

  return `@echo off
setlocal enabledelayedexpansion

:: ============================================================
::  LaunchQuiz.bat — Auto-generated by QuizMaster
::  Quiz : ${safeName}
::  ID   : ${quizId}
::
::  This launcher reads quizmaster.conf from the quiz root folder
::  (one level up) to locate the QuizMaster installation.
::  If QuizMaster has moved, update quizmaster.conf or open
::  QuizMaster and regenerate this launcher from the Quiz Library.
:: ============================================================

set "QUIZ_ID=${quizId}"
set "PORT=${port}"

:: --- Find QuizMaster via shared config one level up ---
set "CONF=%~dp0..\\${CONF_FILENAME}"
if not exist "%CONF%" (
    echo.
    echo  ERROR: Cannot find quizmaster.conf
    echo  Expected location: %CONF%
    echo.
    echo  To fix this, open QuizMaster and use
    echo  "Regenerate Launchers" in Settings.
    echo.
    pause
    exit /b 1
)
set /p QUIZMASTER_DIR=<"%CONF%"
if "%QUIZMASTER_DIR%"=="" (
    echo  ERROR: quizmaster.conf is empty.
    pause
    exit /b 1
)

:: --- Check if QuizMaster server is already running ---
curl -s -f "http://localhost:%PORT%/api/health" >NUL 2>&1
if %ERRORLEVEL% EQU 0 (
    echo  QuizMaster is already running on port %PORT%.
    start "" "http://localhost:%PORT%/host/%QUIZ_ID%"
    goto :end
)

:: --- Check Node.js ---
where node >NUL 2>&1
if %ERRORLEVEL% NEQ 0 (
    echo.
    echo  ERROR: Node.js is not installed or not on PATH.
    echo  Please install Node.js from: https://nodejs.org
    echo  Choose the LTS version, then run this again.
    echo.
    pause
    exit /b 1
)

:: --- Start QuizMaster server in a new window ---
start "QuizMaster Server" /d "%QUIZMASTER_DIR%" cmd /c "node server.js && pause"

:: --- Wait for server to start ---
echo  Starting QuizMaster server...
:waitloop
timeout /t 1 /nobreak >NUL
curl -s -f "http://localhost:%PORT%/api/health" >NUL 2>&1
if %ERRORLEVEL% NEQ 0 goto :waitloop

:: --- Open the host UI for this quiz ---
start "" "http://localhost:%PORT%/host/%QUIZ_ID%"

:end
endlocal
`;
}

module.exports = { writeConf, readConf, generateLauncher, removeLauncher, CONF_FILENAME, BAT_FILENAME };
